use barsql_core::{DriverType, Identity, PrimaryKey, SqlDialect, StructColumn, StructIndex, TableStructure};

use super::{Changes, Draft, ddl_column};
use crate::alter::{drop_column, rename_column};
use crate::ddl::{compose_create_table, render_column};
use crate::quote::{quote_ident, quote_ident_list, quote_literal_in, table_ref};

pub(super) fn alter(driver: &DriverType, original: &TableStructure, changes: &Changes) -> Vec<String> {
    let (schema, name) = (original.schema.as_str(), original.name.as_str());
    let table = table_ref(driver, schema, name);
    let mut out = Vec::new();
    if let Some((Some(old), _)) = &changes.primary_key
        && !old.name.is_empty()
    {
        out.push(format!("ALTER TABLE {table} DROP CONSTRAINT {}", quote_ident(driver, &old.name)));
    }
    // Indexes go before the columns they cover and come back after the columns they need.
    for index in &changes.dropped_indexes {
        out.push(match index.constraint {
            true => format!("ALTER TABLE {table} DROP CONSTRAINT {}", quote_ident(driver, &index.name)),
            false => format!("DROP INDEX {}", table_ref(driver, schema, &index.name)),
        });
    }
    for (old, new) in &changes.renamed {
        out.push(rename_column(driver, schema, name, old, new));
    }
    for (old, new) in &changes.modified {
        let column = quote_ident(driver, &new.name);
        let alter = |what: &str| format!("ALTER TABLE {table} ALTER COLUMN {column} {what}");
        if old.data_type != new.data_type || old.collation != new.collation {
            let collate = match new.collation.as_str() {
                "" => String::new(),
                collation => format!(" COLLATE {}", quote_ident(driver, collation)),
            };
            out.push(alter(&format!("TYPE {}{collate} USING {column}::{}", new.data_type, new.data_type)));
        }
        if old.nullable != new.nullable {
            out.push(alter(if new.nullable { "DROP NOT NULL" } else { "SET NOT NULL" }));
        }
        if old.default != new.default {
            out.push(match new.default.as_str() {
                "" => alter("DROP DEFAULT"),
                default => alter(&format!("SET DEFAULT {default}")),
            });
        }
        if let Some(change) = identity_change(old.identity, new.identity) {
            out.push(alter(change));
        }
    }
    for column in &changes.dropped {
        out.push(drop_column(driver, schema, name, &column.name, false));
    }
    for column in &changes.added {
        out.push(format!("ALTER TABLE {table} ADD COLUMN {}", render_column(driver, &ddl_column(column))));
    }
    if let Some((_, Some(key))) = &changes.primary_key {
        out.push(format!("ALTER TABLE {table} ADD {}", primary_key(driver, key)));
    }
    out.extend(changes.added_indexes.iter().map(|index| create_index(driver, &table, index)));
    let commented = changes.modified.iter().filter(|(old, new)| old.comment != new.comment).map(|(_, new)| new);
    let added = changes.added.iter().filter(|column| !column.comment.is_empty());
    out.extend(commented.chain(added).map(|column| comment(driver, schema, name, column)));
    out
}

pub(super) fn create(driver: &DriverType, draft: &Draft) -> Vec<String> {
    let live: Vec<&StructColumn> = draft.columns.iter().filter(|row| !row.dropped).map(|row| &row.column).collect();
    let columns: Vec<_> = live.iter().map(|column| ddl_column(column)).collect();
    let keys = draft.primary_columns();
    let constraints = match keys.is_empty() {
        true => Vec::new(),
        false => vec![primary_key(driver, &PrimaryKey { name: String::new(), columns: keys })],
    };
    let create = compose_create_table(driver, &draft.schema, &draft.name, &columns, &constraints);
    let mut out = vec![create.trim_end_matches(';').to_string()];
    let commented = live.iter().filter(|column| !column.comment.is_empty());
    out.extend(commented.map(|column| comment(driver, &draft.schema, &draft.name, column)));
    out
}

fn identity_change(old: Identity, new: Identity) -> Option<&'static str> {
    Some(match (old, new) {
        (Identity::None, Identity::ByDefault) => "ADD GENERATED BY DEFAULT AS IDENTITY",
        (Identity::None, Identity::Always) => "ADD GENERATED ALWAYS AS IDENTITY",
        (Identity::ByDefault, Identity::Always) => "SET GENERATED ALWAYS",
        (Identity::Always, Identity::ByDefault) => "SET GENERATED BY DEFAULT",
        (Identity::ByDefault | Identity::Always, Identity::None) => "DROP IDENTITY",
        _ => return None,
    })
}

fn create_index(driver: &DriverType, table: &str, index: &StructIndex) -> String {
    let (name, columns) = (quote_ident(driver, &index.name), quote_ident_list(driver, &index.columns));
    if index.constraint && index.unique {
        return format!("ALTER TABLE {table} ADD CONSTRAINT {name} UNIQUE ({columns})");
    }
    let unique = if index.unique { "UNIQUE " } else { "" };
    let method = match index.method.as_str() {
        "" => String::new(),
        method => format!(" USING {method}"),
    };
    format!("CREATE {unique}INDEX {name} ON {table}{method} ({columns})")
}

fn primary_key(driver: &DriverType, key: &PrimaryKey) -> String {
    let columns = quote_ident_list(driver, &key.columns);
    match key.name.as_str() {
        "" => format!("PRIMARY KEY ({columns})"),
        name => format!("CONSTRAINT {} PRIMARY KEY ({columns})", quote_ident(driver, name)),
    }
}

fn comment(driver: &DriverType, schema: &str, table: &str, column: &StructColumn) -> String {
    let text = match column.comment.as_str() {
        "" => "NULL".to_string(),
        text => quote_literal_in(SqlDialect::Postgres, text),
    };
    format!("COMMENT ON COLUMN {}.{} IS {text}", table_ref(driver, schema, table), quote_ident(driver, &column.name))
}

#[cfg(test)]
mod tests {
    use barsql_core::{Identity, StructColumn, StructIndex};

    use crate::structure::fixtures::*;
    use crate::structure::{Draft, Row, plan_changes, plan_create};

    #[test]
    fn postgres_alters_columns_and_comments() {
        let original = users();
        let mut draft = Draft::from_structure(&original);
        draft.rename_column(1, "full_name".into());
        let email = &mut draft.columns[2].column;
        email.data_type = "varchar(320)".into();
        email.nullable = false;
        email.comment = "Login address".into();
        draft.columns[3].column.default = "'active'".into();
        draft.columns[4].dropped = true;
        draft.columns.push(added(StructColumn { nullable: false, default: "0".into(), ..column("age", "integer") }));
        let plan = plan_changes(&PG, &original, &draft).expect("valid");
        assert_eq!(
            sql(&plan),
            [
                "BEGIN",
                r#"ALTER TABLE "public"."users" RENAME COLUMN "name" TO "full_name""#,
                r#"ALTER TABLE "public"."users" ALTER COLUMN "email" TYPE varchar(320) USING "email"::varchar(320)"#,
                r#"ALTER TABLE "public"."users" ALTER COLUMN "email" SET NOT NULL"#,
                r#"ALTER TABLE "public"."users" ALTER COLUMN "status" SET DEFAULT 'active'"#,
                r#"ALTER TABLE "public"."users" DROP COLUMN "legacy""#,
                r#"ALTER TABLE "public"."users" ADD COLUMN "age" integer DEFAULT 0 NOT NULL"#,
                r#"COMMENT ON COLUMN "public"."users"."email" IS 'Login address'"#,
                "COMMIT",
            ]
        );
    }

    #[test]
    fn postgres_changes_identity_and_the_primary_key() {
        let mut original = users();
        original.columns.push(StructColumn { nullable: false, ..column("num", "integer") });
        let mut draft = Draft::from_structure(&original);
        draft.columns[0].column.identity = Identity::Always;
        draft.columns[5].column.identity = Identity::ByDefault;
        draft.columns[5].primary = true;
        let plan = plan_changes(&PG, &original, &draft).expect("valid");
        assert_eq!(
            sql(&plan)[1..sql(&plan).len() - 1],
            [
                r#"ALTER TABLE "public"."users" DROP CONSTRAINT "users_pkey""#,
                r#"ALTER TABLE "public"."users" ALTER COLUMN "id" SET GENERATED ALWAYS"#,
                r#"ALTER TABLE "public"."users" ALTER COLUMN "num" ADD GENERATED BY DEFAULT AS IDENTITY"#,
                r#"ALTER TABLE "public"."users" ADD CONSTRAINT "users_pkey" PRIMARY KEY ("id", "num")"#,
            ]
        );
    }

    #[test]
    fn postgres_quotes_awkward_names_and_keeps_defaults_as_typed() {
        let mut original = users();
        original.columns.push(column("we\"ird", "text"));
        let mut draft = Draft::from_structure(&original);
        draft.rename_column(5, "Mixed Case".into());
        draft.columns.push(added(StructColumn { default: "nextval('s'::regclass)".into(), ..column("order", "int") }));
        let plan = plan_changes(&PG, &original, &draft).expect("valid");
        let steps = sql(&plan);
        assert!(
            steps.contains(&r#"ALTER TABLE "public"."users" RENAME COLUMN "we""ird" TO "Mixed Case""#),
            "{steps:?}"
        );
        assert!(
            steps.contains(&r#"ALTER TABLE "public"."users" ADD COLUMN "order" int DEFAULT nextval('s'::regclass)"#),
            "{steps:?}"
        );
    }

    #[test]
    fn postgres_adds_and_drops_indexes() {
        let mut original = users();
        original.indexes = vec![
            StructIndex { method: "btree".into(), ..index("users_name_idx", &["name"], false) },
            StructIndex { constraint: true, ..index("users_status_key", &["status"], true) },
        ];
        let mut draft = Draft::from_structure(&original);
        draft.indexes[0].dropped = true;
        draft.indexes[1].dropped = true;
        let email = StructIndex { method: "btree".into(), ..index("users_email_idx", &["email"], true) };
        draft.indexes.push(Row::added(email));
        let plan = plan_changes(&PG, &original, &draft).expect("valid");
        assert_eq!(
            sql(&plan),
            [
                "BEGIN",
                r#"DROP INDEX "public"."users_name_idx""#,
                r#"ALTER TABLE "public"."users" DROP CONSTRAINT "users_status_key""#,
                r#"CREATE UNIQUE INDEX "users_email_idx" ON "public"."users" USING btree ("email")"#,
                "COMMIT",
            ]
        );
    }

    #[test]
    fn postgres_drops_indexes_before_columns_and_creates_them_last() {
        let mut original = users();
        original.indexes = vec![index("users_legacy_idx", &["legacy"], false)];
        let mut draft = Draft::from_structure(&original);
        draft.indexes[0].dropped = true;
        draft.columns[4].dropped = true;
        draft.rename_column(1, "full_name".into());
        draft.indexes.push(Row::added(index("users_full_name_idx", &["full_name"], false)));
        let plan = plan_changes(&PG, &original, &draft).expect("valid");
        let steps = sql(&plan);
        assert_eq!(
            steps[1..steps.len() - 1],
            [
                r#"DROP INDEX "public"."users_legacy_idx""#,
                r#"ALTER TABLE "public"."users" RENAME COLUMN "name" TO "full_name""#,
                r#"ALTER TABLE "public"."users" DROP COLUMN "legacy""#,
                r#"CREATE INDEX "users_full_name_idx" ON "public"."users" ("full_name")"#,
            ]
        );
    }

    #[test]
    fn postgres_creates_a_table() {
        let mut draft = Draft::new_table(&PG, "public");
        draft.name = "people".into();
        let email = StructColumn { nullable: false, comment: "Login".into(), ..column("email", "text") };
        draft.columns.push(added(email));
        let plan = plan_create(&PG, &draft).expect("valid");
        assert_eq!(
            sql(&plan),
            [
                "BEGIN",
                "CREATE TABLE \"public\".\"people\" (\n    \"id\" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,\n    \"email\" text NOT NULL,\n    PRIMARY KEY (\"id\")\n)",
                r#"COMMENT ON COLUMN "public"."people"."email" IS 'Login'"#,
                "COMMIT",
            ]
        );
    }
}
