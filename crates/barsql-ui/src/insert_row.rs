#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Mode {
    Default,
    Null,
    Value,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Invalid {
    Required,
    NotNullable,
    EmptyInsert,
}

fn starts_with_ignore_case(text: &str, prefix: &str) -> bool {
    text.len() >= prefix.len() && text.as_bytes()[..prefix.len()].eq_ignore_ascii_case(prefix.as_bytes())
}

// Sequences, identities and computed columns fill themselves in. SQLite's rowid alias comes marked as an identity.
pub fn auto_generated(col: &ColumnInfo) -> bool {
    if col.is_identity || col.is_computed {
        return true;
    }
    if col.default_val.is_empty() {
        let serial = ["serial", "bigserial", "smallserial"].iter().any(|s| starts_with_ignore_case(&col.data_type, s));
        return col.is_primary && serial;
    }
    let default = col.default_val.to_lowercase();
    ["nextval(", "autoincrement", "auto_increment", "generated always", "generated by default"]
        .iter()
        .any(|marker| default.contains(marker))
}

fn has_default(col: &ColumnInfo) -> bool {
    auto_generated(col) || !col.default_val.trim().is_empty()
}

pub fn requires_value(col: &ColumnInfo) -> bool {
    !auto_generated(col) && !col.is_nullable && !has_default(col)
}

pub fn can_default(col: &ColumnInfo) -> bool {
    has_default(col) || col.is_nullable
}

pub fn initial_mode(col: &ColumnInfo) -> Mode {
    if has_default(col) || col.is_nullable { Mode::Default } else { Mode::Value }
}

pub fn default_hint(col: &ColumnInfo) -> String {
    let default = col.default_val.trim();
    if auto_generated(col) {
        return if default.is_empty() { col.data_type.clone() } else { default.to_string() };
    }
    let chars: Vec<char> = default.chars().collect();
    if chars.len() > 72 { format!("{}…", chars[..72].iter().collect::<String>()) } else { default.to_string() }
}

pub fn validate(columns: &[ColumnInfo], fields: &BTreeMap<String, (Mode, String)>) -> Option<Invalid> {
    let mut included = 0;
    for col in columns {
        let Some((mode, value)) = fields.get(&col.name) else { continue };
        if auto_generated(col) {
            continue;
        }
        match mode {
            Mode::Default => {
                if !can_default(col) || requires_value(col) {
                    return Some(Invalid::Required);
                }
            }
            Mode::Null => {
                included += 1;
                if !col.is_nullable {
                    return Some(Invalid::NotNullable);
                }
            }
            Mode::Value => {
                included += 1;
                if value.trim().is_empty() && requires_value(col) {
                    return Some(Invalid::Required);
                }
            }
        }
    }
    (included == 0).then_some(Invalid::EmptyInsert)
}

pub fn payload(columns: &[ColumnInfo], fields: &BTreeMap<String, (Mode, String)>) -> Row {
    columns
        .iter()
        .filter(|col| !auto_generated(col))
        .filter_map(|col| match fields.get(&col.name)? {
            (Mode::Default, _) => None,
            (Mode::Null, _) => Some((col.name.clone(), Value::Null)),
            (Mode::Value, value) => Some((col.name.clone(), Value::Text(value.clone()))),
        })
        .collect()
}

type OnInserted = Rc<dyn Fn(&mut Window, &mut App)>;

pub struct InsertRowForm {
    connection: ConnectionConfig,
    schema: String,
    table: String,
    columns: Vec<ColumnInfo>,
    modes: BTreeMap<String, Mode>,
    inputs: BTreeMap<String, Entity<InputState>>,
    loading: bool,
    saving: bool,
    error: Option<SharedString>,
    invalid: Option<Invalid>,
    on_inserted: OnInserted,
    scroll: ScrollHandle,
}

impl InsertRowForm {
    fn new(
        connection: ConnectionConfig,
        schema: String,
        table: String,
        on_inserted: OnInserted,
        cx: &mut Context<Self>,
    ) -> Self {
        let load = {
            let bar = state::bar(cx);
            let (id, schema, table) = (connection.id.clone(), schema.clone(), table.clone());
            state::spawn(cx, async move { bar.list_columns(&id, &schema, &table).await })
        };
        cx.spawn(async move |this, cx| {
            let result = load.await;
            this.update(cx, |form, cx| {
                form.loading = false;
                match result {
                    Some(Ok(columns)) => form.columns = columns,
                    Some(Err(error)) => form.error = Some(error.message.into()),
                    None => {}
                }
                cx.notify();
            })
            .ok();
        })
        .detach();
        Self {
            connection,
            schema,
            table,
            columns: Vec::new(),
            modes: BTreeMap::new(),
            inputs: BTreeMap::new(),
            loading: true,
            saving: false,
            error: None,
            invalid: None,
            on_inserted,
            scroll: ScrollHandle::new(),
        }
    }

    fn mode(&self, col: &ColumnInfo) -> Mode {
        self.modes.get(&col.name).copied().unwrap_or_else(|| initial_mode(col))
    }

    fn fields(&self, cx: &App) -> BTreeMap<String, (Mode, String)> {
        self.columns
            .iter()
            .map(|col| {
                let value =
                    self.inputs.get(&col.name).map(|input| input.read(cx).value().to_string()).unwrap_or_default();
                (col.name.clone(), (self.mode(col), value))
            })
            .collect()
    }

    fn ready(&self) -> bool {
        !self.loading && !self.saving && !self.columns.is_empty()
    }

    fn submit(&mut self, window: &mut Window, cx: &mut Context<Self>) {
        if !self.ready() {
            return;
        }
        let fields = self.fields(cx);
        self.invalid = validate(&self.columns, &fields);
        if self.invalid.is_some() {
            cx.notify();
            return;
        }
        let values = payload(&self.columns, &fields);
        self.saving = true;
        self.error = None;
        cx.notify();
        let bar = state::bar(cx);
        let (id, schema, table) = (self.connection.id.clone(), self.schema.clone(), self.table.clone());
        let insert = state::spawn(cx, async move { bar.insert_row(&id, &schema, &table, &values).await });
        cx.spawn_in(window, async move |this, cx| {
            let result = insert.await;
            this.update_in(cx, |form, window, cx| {
                form.saving = false;
                match result {
                    Some(Ok(_)) => {
                        window.close_dialog(cx);
                        (form.on_inserted)(window, cx);
                    }
                    Some(Err(error)) => form.error = Some(error.message.into()),
                    None => {}
                }
                cx.notify();
            })
            .ok();
        })
        .detach();
    }

    fn input(&mut self, col: &ColumnInfo, window: &mut Window, cx: &mut Context<Self>) -> Entity<InputState> {
        if let Some(input) = self.inputs.get(&col.name) {
            return input.clone();
        }
        let input = cx.new(|cx| InputState::new(window, cx));
        self.inputs.insert(col.name.clone(), input.clone());
        input
    }

    fn set_mode(&mut self, name: String, mode: Mode, window: &mut Window, cx: &mut Context<Self>) {
        if mode != Mode::Value
            && let Some(input) = self.inputs.get(&name)
        {
            input.update(cx, |state, cx| state.set_value("", window, cx));
        }
        self.modes.insert(name, mode);
        self.invalid = None;
        cx.notify();
    }

    // Into the field's input, which the insert reads.
    fn pick_value(&mut self, name: &str, value: String, window: &mut Window, cx: &mut Context<Self>) {
        if let Some(input) = self.inputs.get(name) {
            input.update(cx, |state, cx| state.set_value(value, window, cx));
        }
        self.invalid = None;
        cx.notify();
    }

    // In place of the text field, for a column whose values come from a list.
    fn value_select(
        &self,
        col: &ColumnInfo,
        input: &Entity<InputState>,
        placeholder: SharedString,
        enabled: bool,
        window: &mut Window,
        cx: &mut Context<Self>,
    ) -> impl IntoElement + use<> {
        let value = input.read(cx).value().to_string();
        let id = format!("insert-value-{}", col.name);
        let select = match value.is_empty() {
            true => form::select_placeholder(SharedString::from(id.clone()), placeholder, cx),
            false => form::select(SharedString::from(id.clone()), value.clone(), cx),
        };
        let (this, name, values) = (cx.entity().downgrade(), col.name.clone(), col.enum_values.clone());
        select.debug_selector(move || id).disabled(!enabled).select_menu(window, cx, move |mut menu, _, _| {
            for option in &values {
                let (this, name, option) = (this.clone(), name.clone(), option.clone());
                let item = PopupMenuItem::new(option.clone()).checked(option == value);
                menu = menu.item(item.on_click(move |_, window, cx| {
                    this.update(cx, |form, cx| form.pick_value(&name, option.clone(), window, cx)).ok();
                }));
            }
            menu
        })
    }

    fn field(&mut self, col: ColumnInfo, window: &mut Window, cx: &mut Context<Self>) -> impl IntoElement {
        let mode = self.mode(&col);
        let hidden = auto_generated(&col);
        let hint = default_hint(&col);
        let input = self.input(&col, window, cx);
        let placeholder: SharedString = if hidden {
            if hint.is_empty() { t(cx, "tableView.addRowDialog.autoGenerated") } else { hint.clone().into() }
        } else {
            match mode {
                Mode::Default if !hint.is_empty() => hint.clone().into(),
                Mode::Default if col.is_nullable => t(cx, "tableView.addRowDialog.defaultOmitNullable"),
                Mode::Default => t(cx, "tableView.addRowDialog.inputPlaceholderDefault"),
                Mode::Null => t(cx, "tableView.addRowDialog.inputPlaceholderNull"),
                Mode::Value if !col.enum_values.is_empty() => t(cx, "tableView.addRowDialog.choosePlaceholder"),
                Mode::Value => t(cx, "tableView.addRowDialog.inputPlaceholderValue"),
            }
        };
        input.update(cx, |state, cx| state.set_placeholder(placeholder.clone(), window, cx));
        let enabled = !self.saving && !hidden && mode == Mode::Value;
        let theme = cx.theme();
        let badge = |text: SharedString, color: Hsla| form::badge(text, color);
        let mut modes = Vec::new();
        if can_default(&col) {
            modes.push((Mode::Default, t(cx, "tableView.addRowDialog.modeDefault")));
        }
        if col.is_nullable {
            modes.push((Mode::Null, t(cx, "common.null")));
        }
        modes.push((Mode::Value, t(cx, "tableView.addRowDialog.modeValue")));
        let current = modes.iter().find(|(m, _)| *m == mode).map(|(_, label)| label.clone()).unwrap_or_default();
        let this = cx.entity().downgrade();
        let name = col.name.clone();
        let picker = (!hidden && modes.len() > 1).then(|| {
            form::select_small(SharedString::from(format!("insert-mode-{}", col.name)), current, cx)
                .debug_selector({
                    let selector = format!("insert-mode-{}", col.name);
                    move || selector
                })
                .disabled(self.saving)
                .dropdown_menu(move |mut menu: PopupMenu, _, _| {
                    for (option, label) in modes.clone() {
                        let (this, name) = (this.clone(), name.clone());
                        menu = menu.item(PopupMenuItem::new(label).checked(option == mode).on_click(
                            move |_, window, cx| {
                                this.update(cx, |form, cx| form.set_mode(name.clone(), option, window, cx)).ok();
                            },
                        ));
                    }
                    menu
                })
        });
        let (muted, warning) = (theme.muted_foreground, theme.warning);
        let control = match col.enum_values.is_empty() {
            true => div()
                .debug_selector({
                    let selector = format!("insert-field-{}", col.name);
                    move || selector
                })
                .child(form::input(&input, window, cx).disabled(!enabled))
                .into_any_element(),
            false => self.value_select(&col, &input, placeholder, enabled, window, cx).into_any_element(),
        };
        v_flex()
            .gap(rems(0.308))
            .child(
                h_flex()
                    .justify_between()
                    .gap(rems(0.615))
                    .mb(rems(0.154))
                    .child(
                        h_flex()
                            .flex_wrap()
                            .gap(rems(0.385))
                            .min_w_0()
                            .child(div().text_size(TEXT_SM).font_medium().child(col.name.clone()))
                            .child(
                                div()
                                    .text_size(TEXT_XS)
                                    .text_color(muted)
                                    .child(display_type(self.connection.driver.dialect(), &col.data_type)),
                            ),
                    )
                    .child(
                        h_flex()
                            .flex_none()
                            .gap(rems(0.462))
                            .child(
                                h_flex()
                                    .gap(rems(0.308))
                                    .when(col.is_primary, |el| {
                                        el.child(badge(t(cx, "tableView.addRowDialog.primaryKeyBadge"), muted))
                                    })
                                    .when(col.is_foreign, |el| {
                                        el.child(badge(t(cx, "tableView.addRowDialog.foreignKeyBadge"), muted))
                                    })
                                    .when(requires_value(&col), |el| {
                                        el.child(badge(t(cx, "tableView.addRowDialog.requiredBadge"), warning))
                                    }),
                            )
                            .children(picker),
                    ),
            )
            .child(control)
    }
}

impl Render for InsertRowForm {
    fn render(&mut self, window: &mut Window, cx: &mut Context<Self>) -> impl IntoElement {
        let body = if self.loading {
            modal::body().child(div().text_size(TEXT_SM).child(t(cx, "tableView.addRowDialog.loading")))
        } else {
            let message = self.invalid.map(|invalid| match invalid {
                Invalid::Required => t(cx, "tableView.addRowDialog.errorRequired"),
                Invalid::NotNullable => t(cx, "tableView.addRowDialog.errorNotNullable"),
                Invalid::EmptyInsert => t(cx, "tableView.addRowDialog.errorEmpty"),
            });
            let fields: Vec<AnyElement> =
                self.columns.clone().into_iter().map(|col| self.field(col, window, cx).into_any_element()).collect();
            modal::body()
                .children(self.error.clone().map(|error| form::error(error, cx)))
                .children(message.map(|message| form::error(message, cx)))
                .child(v_flex().gap(rems(0.923)).mt(rems(0.615)).children(fields))
        };
        let (ready, saving) = (self.ready(), self.saving);
        modal::scroll_content().child(modal::scroll_body(&self.scroll, body)).child(
            modal::footer(cx)
                .child(
                    Button::new("insert-row-cancel")
                        .large()
                        .label(t(cx, "common.cancel"))
                        .disabled(saving)
                        .on_click(|_, window, cx| window.close_dialog(cx)),
                )
                .child(
                    Button::new("insert-row-submit")
                        .large()
                        .debug_selector(|| "insert-row-submit".into())
                        .primary()
                        .label(t(cx, "tableView.addRowDialog.submit"))
                        .disabled(!ready)
                        .on_click(cx.listener(|form, _, window, cx| form.submit(window, cx))),
                ),
        )
    }
}

pub fn open(
    connection: ConnectionConfig,
    schema: String,
    table: String,
    window: &mut Window,
    cx: &mut App,
    on_inserted: impl Fn(&mut Window, &mut App) + 'static,
) {
    let title = t_with(cx, "tableView.addRowDialog.title", &[("table", &table)]);
    let form = cx.new(|cx| InsertRowForm::new(connection, schema, table, Rc::new(on_inserted), cx));
    window.open_dialog(cx, move |dialog, window, cx| {
        let entry = form.clone();
        Modal::new("insert-row", title.clone()).build(dialog, form.clone(), window, cx).on_ok(move |_, window, cx| {
            entry.update(cx, |form, cx| form.submit(window, cx));
            false
        })
    });
}

#[cfg(test)]
mod tests {
    use std::collections::BTreeMap;

    use barsql_core::{ColumnInfo, Row, Value};

    use super::{Invalid, Mode, auto_generated, initial_mode, payload, requires_value, validate};

    fn col(name: &str, data_type: &str, nullable: bool, primary: bool, default: &str) -> ColumnInfo {
        ColumnInfo {
            name: name.into(),
            data_type: data_type.into(),
            is_nullable: nullable,
            is_primary: primary,
            default_val: default.into(),
            ..Default::default()
        }
    }

    fn cols() -> Vec<ColumnInfo> {
        vec![
            col("id", "integer", false, true, "nextval('id_seq'::regclass)"),
            col("email", "varchar", false, false, ""),
            col("note", "text", true, false, ""),
        ]
    }

    fn initial(columns: &[ColumnInfo]) -> BTreeMap<String, (Mode, String)> {
        columns.iter().map(|c| (c.name.clone(), (initial_mode(c), String::new()))).collect()
    }

    #[test]
    fn auto_generated_columns_are_the_ones_the_catalog_or_a_default_marks() {
        assert!(auto_generated(&cols()[0]));
        assert!(!auto_generated(&cols()[1]));
        let int_pk = col("id", "integer", false, true, "");
        assert!(!auto_generated(&int_pk) && requires_value(&int_pk));
        assert!(auto_generated(&ColumnInfo { is_identity: true, ..int_pk }));
        assert!(auto_generated(&col("id", "int", false, true, "auto_increment")));
        assert!(auto_generated(&col("id", "serial", false, true, "")));
    }

    #[test]
    fn composite_integer_keys_take_their_values() {
        let pair = vec![col("left_id", "INTEGER", false, true, ""), col("right_id", "INTEGER", false, true, "")];
        assert!(pair.iter().all(|c| !auto_generated(c) && requires_value(c)));
        let mut fields = initial(&pair);
        assert_eq!(validate(&pair, &fields), Some(Invalid::Required));
        fields.insert("left_id".into(), (Mode::Value, "1".into()));
        fields.insert("right_id".into(), (Mode::Value, "2".into()));
        assert_eq!(validate(&pair, &fields), None);
        assert_eq!(
            payload(&pair, &fields),
            Row::from([("left_id".into(), Value::Text("1".into())), ("right_id".into(), Value::Text("2".into()))])
        );
    }

    #[test]
    fn modes_start_at_the_default_when_there_is_one() {
        assert_eq!(cols().iter().map(initial_mode).collect::<Vec<_>>(), [Mode::Default, Mode::Value, Mode::Default]);
        let fk = ColumnInfo { is_foreign: true, ..col("user_id", "integer", true, false, "") };
        assert!(!requires_value(&fk) && !auto_generated(&fk));
    }

    #[test]
    fn fields_validate_and_build_the_insert() {
        let nullable = vec![col("a", "text", true, false, ""), col("b", "text", true, false, "")];
        assert_eq!(validate(&nullable, &initial(&nullable)), Some(Invalid::EmptyInsert));
        let mut fields = initial(&cols());
        assert_eq!(validate(&cols(), &fields), Some(Invalid::Required));
        fields.insert("email".into(), (Mode::Value, "a@b.c".into()));
        fields.insert("note".into(), (Mode::Null, String::new()));
        assert_eq!(validate(&cols(), &fields), None);
        assert_eq!(
            payload(&cols(), &fields),
            Row::from([("email".into(), Value::Text("a@b.c".into())), ("note".into(), Value::Null)])
        );
        fields.insert("email".into(), (Mode::Null, String::new()));
        assert_eq!(validate(&cols(), &fields), Some(Invalid::NotNullable));
    }
}
